import json
import os
import sys
import pandas as pd
import pytest

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from attack_graph import build_attack_graph, calculate_blast_radius, get_plotly_network_figure
from remediation import generate_remediation_payload, RemediationType
from copilot import generate_incident_briefing, ask_copilot
from compliance import calculate_framework_posture, export_audit_report
from engine import analyze_and_predict_drift, run_cross_domain_correlator

def evaluate_all():
    findings = []
    print("=== STARTING DRIFTSHIELD EVALUATION ===")

    # 1. Load Data
    if not os.path.exists("baseline_controls.json"):
        findings.append("ERROR: baseline_controls.json is missing.")
        return findings
    with open("baseline_controls.json", "r") as f:
        baselines = json.load(f)

    if not os.path.exists("drift_event_labels.csv"):
        findings.append("ERROR: drift_event_labels.csv is missing.")
        return findings
    df = pd.read_csv("drift_event_labels.csv")

    print(f"[DATA] Total Events: {len(df)}, Controls in Baseline: {len(baselines)}")

    # 2. Test Edge Case: Empty DataFrame (e.g. user deselects all filters)
    df_empty = df.iloc[0:0].copy()
    try:
        G_empty, stats_empty = build_attack_graph(df_empty)
        fig_empty = get_plotly_network_figure(G_empty)
        print("[TEST] build_attack_graph with empty DataFrame: PASS")
    except Exception as e:
        findings.append(f"BUG in attack_graph with empty dataframe: {e}")

    try:
        posture_empty = calculate_framework_posture(df_empty, baselines)
        report_empty = export_audit_report(posture_empty)
        print("[TEST] calculate_framework_posture with empty DataFrame: PASS")
    except Exception as e:
        findings.append(f"BUG in compliance with empty dataframe: {e}")

    # 3. Test Attack Graph with Real Data
    try:
        G, stats = build_attack_graph(df)
        fig = get_plotly_network_figure(G)
        print(f"[TEST] Real Attack Graph: Nodes={stats['active_threat_nodes']}, Edges={stats['attack_paths']}")
        if stats['active_threat_nodes'] == 0:
            findings.append("WARNING: Attack graph produced 0 threat nodes from active dataset.")
    except Exception as e:
        findings.append(f"BUG in real attack graph execution: {e}")

    # 4. Test Blast Radius Engine
    try:
        score_low, factors_low = calculate_blast_radius(0, 0, False, False)
        score_high, factors_high = calculate_blast_radius(10, 4, True, True)
        assert 0 <= score_low <= 100
        assert 0 <= score_high <= 100
        assert score_high > score_low
        print(f"[TEST] Blast Radius Calculation: Min={score_low}, Max={score_high} PASS")
    except Exception as e:
        findings.append(f"BUG in calculate_blast_radius: {e}")

    # 5. Test Remediation Payloads across ALL Baseline Controls
    remediation_fails = []
    types_found = set()
    for cid, rule in baselines.items():
        try:
            payload = generate_remediation_payload(rule, observed_value="test_drifted")
            types_found.add(payload["remediation_type"])
            if not payload.get("code_snippet"):
                remediation_fails.append(f"Missing code_snippet for {cid}")
            if not payload.get("rollback_diff"):
                remediation_fails.append(f"Missing rollback_diff for {cid}")
        except Exception as e:
            remediation_fails.append(f"Crash on {cid}: {e}")

    if remediation_fails:
        findings.append(f"BUG in remediation.py for {len(remediation_fails)} controls: {remediation_fails[:5]}")
    else:
        print(f"[TEST] All {len(baselines)} baseline controls successfully generate remediation playbooks! Types: {types_found}")

    # 6. Test Compound Correlator & Copilot
    try:
        compounds = run_cross_domain_correlator(df)
        print(f"[TEST] Correlator found {len(compounds)} compound incidents.")
        if compounds:
            briefing = generate_incident_briefing(compounds[0])
            assert "Executive Summary" in briefing["markdown_report"]
            print("[TEST] AI Copilot Threat Briefing: PASS")
        else:
            findings.append("NOTE: No compound cross-domain incidents generated by correlator.")
    except Exception as e:
        findings.append(f"BUG in correlator/copilot briefing: {e}")

    # 7. Test Copilot Q&A
    context = {
        "total_drifts": len(df),
        "critical_alerts": len(df[(df["predicted_risky"] == 1) & (df["severity"] == "CRITICAL")]),
        "high_alerts": len(df[(df["predicted_risky"] == 1) & (df["severity"] == "HIGH")])
    }
    sample_queries = [
        "What should I triage first?",
        "What is the current blast radius?",
        "Show compliance audit summary",
        "How do I remediate?",
        "Random unexpected question about system status"
    ]
    for q in sample_queries:
        try:
            ans = ask_copilot(q, context)
            assert len(ans) > 10
        except Exception as e:
            findings.append(f"BUG in ask_copilot for query '{q}': {e}")
    print("[TEST] Copilot Q&A across queries: PASS")

    # 8. Test Compliance Engine
    try:
        posture = calculate_framework_posture(df, baselines)
        report_md = export_audit_report(posture)
        for fw in ["NIST SP 800-53", "CIS Benchmarks", "GDPR", "PCI-DSS"]:
            assert fw in posture
            assert "compliance_rate" in posture[fw]
        print("[TEST] Compliance Frameworks & Audit Attestation: PASS")
    except Exception as e:
        findings.append(f"BUG in compliance engine: {e}")

    # 9. Test app.py edge cases:
    # Check if df has predicted_risky == 1 rows
    active_threats = df[df["predicted_risky"] == 1]
    print(f"[STATUS] Active threats in current dataset: {len(active_threats)}")

    print("=== EVALUATION COMPLETE ===")
    return findings

if __name__ == "__main__":
    findings = evaluate_all()
    print("\nFINDINGS SUMMARY:")
    if not findings:
        print("ALL TESTS PASSED. NO CRITICAL BUGS DETECTED.")
    else:
        for f in findings:
            print(f"- {f}")
